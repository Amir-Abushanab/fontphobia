// The plan report's per-page arithmetic (§3), on a hand-made plan: no fonts, no browser.
import { describe, expect, it } from 'vitest';
import { formatPlan, heavierPages, pageBytes, type Plan, type UsageFileJson } from '../src/index.ts';

const KB = 1024;
/** One face: a 60 KB source, split into a 40 KB core (ASCII) and a 30 KB extended file (U+E9). */
const plan = {
  version: 1,
  optIns: [],
  faces: [
    {
      id: 'serif-400-normal',
      family: 'Serif',
      status: 'planned',
      source: { file: 'fonts/serif.woff2', bytes: 60 * KB, sha256: 's' },
      bytes: { now: 40 * KB, core: 40 * KB, ext: 30 * KB },
      files: [
        { role: 'core', name: 'serif.core.woff2', bytes: 40 * KB, unicodeRange: 'U+20-7E' },
        { role: 'ext', name: 'serif.ext.woff2', bytes: 30 * KB, unicodeRange: 'U+E9' },
      ],
    },
  ],
} as unknown as Plan;

const usage = (o: { split: boolean }) =>
  ({
    version: 1,
    faces: {
      'serif-400-normal': {
        family: 'Serif',
        descriptors: {},
        source: { adapter: 'css', note: o.split ? 'generated by fontphobia' : undefined },
      },
    },
    pages: Object.fromEntries(
      (
        [
          ['/', 'U+41-5A'],
          ['/menu/', 'U+41-5A, U+E9'],
        ] as const
      ).map(([page, chars]) => [
        page,
        {
          bytes: 0,
          faces: { 'serif-400-normal': chars },
          // Unsplit, a page loads the source; over an earlier split, that build's core file.
          fonts: [{ url: '/fonts/x.woff2', status: 200, bytes: (o.split ? 38 : 60) * KB, faces: ['serif-400-normal'] }],
        },
      ]),
    ),
  }) as unknown as UsageFileJson;

describe('bytes per page', () => {
  it('a page that draws an extended character pays for the whole extended file', () => {
    const pages = pageBytes(plan, usage({ split: false }));
    expect(pages.map((p) => [p.page, p.now / KB, p.after / KB])).toEqual([
      ['/', 60, 40],
      ['/menu/', 60, 70],
    ]);
    expect(pages[1]!.extra).toEqual([{ face: 'serif-400-normal', role: 'ext', bytes: 30 * KB, chars: [0xe9] }]);
  });

  it('over a site an earlier build split, "before" is still the unsplit file', () => {
    const pages = pageBytes(plan, usage({ split: true }));
    expect(pages.map((p) => p.now / KB)).toEqual([60, 60]);
    const text = formatPlan(plan, usage({ split: true }));
    expect(text).toMatch(/Face\s+Before\s+Core/);
    expect(text).toMatch(/Serif 400 normal\s+60\.0 KB/);
    expect(text).toContain('median 60.0 KB → 40.0 KB (33% less)');
  });

  it('names the pages that would download more than before, and what makes them', () => {
    expect(heavierPages(pageBytes(plan, usage({ split: false }))).map((p) => p.page)).toEqual(['/menu/']);
    const text = formatPlan(plan, usage({ split: false }));
    expect(text).toContain('Pages that would download more than before');
    expect(text).toContain('/menu/  60.0 KB → 70.0 KB (+10.0 KB)');
    expect(text).toContain('Serif 400 normal extended file, 30.0 KB, for 1 character(s) (é)');
  });

  it('says "more" when the median grows, not a negative saving', () => {
    const grown = usage({ split: false });
    for (const page of Object.values(grown.pages)) page.fonts[0]!.bytes = 30 * KB;
    expect(formatPlan(plan, grown)).toContain('(33% more)');
  });
});
