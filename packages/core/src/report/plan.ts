// The plan report (§3 "Shape of the default output"): per-face sizes, per-page bytes before and
// after, skipped faces, the shaping repair's cost and every opt-in with its measured saving.
import { codePointsOf, parseUnicodeRange } from '../css/unicode-range.ts';
import type { FacePlan, Plan, UsageFileJson } from '../plan/planner.ts';
import { kb } from './audit.ts';
import { plainStyle, savedPct, type Style } from './style.ts';

const label = (f: FacePlan, u: UsageFileJson) => {
  const d = u.faces[f.id]?.descriptors ?? {};
  const parts = [f.family, (d['font-weight'] ?? '400').trim(), (d['font-style'] ?? 'normal').trim()];
  // Slices of one family (fontsource, Google): name them by their source file.
  if (d['unicode-range'])
    parts.push(
      `(${
        f.source?.file
          .split('/')
          .pop()
          ?.replace(/\.[a-z0-9]+$/i, '') ?? f.id
      })`,
    );
  return parts.join(' ');
};

export interface PageBytes {
  page: string;
  /**
   * What the page downloaded before fontphobia: the files the audit saw it load, except that for a
   * face an earlier build already split it is the face's source file, once. A plan made over a split
   * site is then still compared with the unsplit site, not with the split before it.
   */
  now: number;
  after: number;
  /** Per face: its own files' bytes now and after. */ faces: Record<string, { now: number; after: number }>;
  /** The files it would load beyond the core files, and the characters that make it. */
  extra: { face: string; role: string; bytes: number; chars: number[] }[];
}

/** A face the audit found already split by an earlier build (the audit names its source file). */
const splitBefore = (usage: UsageFileJson, id: string) => usage.faces[id]?.source.note === 'generated by fontphobia';

/** What each page downloaded before fontphobia and with the plan applied (files load per unicode-range). */
export function pageBytes(plan: Plan, usage: UsageFileJson): PageBytes[] {
  const byId = new Map(plan.faces.map((f) => [f.id, f]));
  const sets = new Map<string, { role: string; set: Set<number>; bytes: number; name: string }[]>();
  for (const f of plan.faces)
    if (f.status === 'planned')
      sets.set(
        f.id,
        (f.files ?? []).map((x) => ({
          role: x.role,
          set: new Set(codePointsOf(parseUnicodeRange(x.unicodeRange))),
          bytes: x.bytes,
          name: x.name,
        })),
      );
  return Object.entries(usage.pages)
    .toSorted(([a], [b]) => (a < b ? -1 : 1))
    .map(([page, pg]) => {
      let now = 0,
        after = 0;
      const loaded = new Set<string>();
      const sources = new Set<string>();
      const faces: PageBytes['faces'] = {};
      const extra: PageBytes['extra'] = [];
      const add = (id: string, k: 'now' | 'after', n: number) => {
        const x = (faces[id] ??= { now: 0, after: 0 });
        x[k] += n;
      };
      for (const font of pg.fonts) {
        if (font.status >= 400) continue;
        // An output of an earlier build stands for the source file it was cut from, counted once
        // however many of its outputs (and faces, when one file backs several) the page loads.
        const earlier =
          font.faces.length > 0 && font.faces.every((id) => splitBefore(usage, id) && byId.get(id)?.source);
        for (const id of earlier ? font.faces : []) {
          const source = byId.get(id)!.source!;
          const first = !sources.has(source.file);
          sources.add(source.file);
          if (first) now += source.bytes;
          if (pg.faces[id] && !faces[id]?.now) add(id, 'now', source.bytes);
        }
        if (!earlier) {
          now += font.bytes;
          // Per face: only pages where it draws (a shared file lists every face it backs).
          for (const id of font.faces) if (pg.faces[id]) add(id, 'now', font.bytes);
        }
        // A file stays as it is unless every face it serves is planned.
        if (!font.faces.length || font.faces.some((id) => byId.get(id)?.status !== 'planned')) {
          after += font.bytes;
          for (const id of font.faces) if (pg.faces[id]) add(id, 'after', font.bytes);
          continue;
        }
        for (const id of font.faces) {
          const chars = [...codePointsOf(parseUnicodeRange(pg.faces[id] ?? ''))];
          for (const file of sets.get(id) ?? []) {
            if (loaded.has(file.name) || !chars.some((c) => file.set.has(c))) continue;
            loaded.add(file.name);
            after += file.bytes;
            add(id, 'after', file.bytes);
            if (file.role !== 'core')
              extra.push({ face: id, role: file.role, bytes: file.bytes, chars: chars.filter((c) => file.set.has(c)) });
          }
        }
      }
      return { page, now, after, faces, extra };
    });
}

/** Pages that would download more font bytes than they did before fontphobia, the worst first. */
export const heavierPages = (pages: PageBytes[]): PageBytes[] =>
  pages.filter((p) => p.after > p.now).toSorted((a, b) => b.after - b.now - (a.after - a.now));

/** "30% less", or "3% more" when it grew. */
const change = (before: number, after: number) => {
  const pct = before ? Math.round(Math.abs(1 - after / before) * 100) : 0;
  return { text: `${pct}% ${after > before ? 'more' : 'less'}`, worse: after > before };
};

const median = (xs: number[]) => {
  const s = [...xs].toSorted((a, b) => a - b);
  return s.length ? s[Math.floor((s.length - 1) / 2)]! : 0;
};
/** Columns padded to their widest cell; `paint` styles a padded cell (row 0 is the header). */
function table(
  rows: string[][],
  align: ('l' | 'r')[],
  paint: (cell: string, col: number, row: number) => string = (c) => c,
): string[] {
  const w = rows[0]!.map((_, i) => Math.max(...rows.map((r) => r[i]!.length)));
  return rows.map((r, y) => {
    const last = r.length - 1;
    return r
      .map((c, i) => paint(align[i] === 'r' ? c.padStart(w[i]!) : i === last ? c : c.padEnd(w[i]!), i, y))
      .join('  ');
  });
}

/** An opt-in the plan measured but didn't apply: what it saves and what it changes. */
export interface OfferedOptIn {
  id: string;
  saving: number;
  faces: number;
  change: string;
}

/** The opt-ins that would save bytes, largest saving first (`--allow <id>` applies one). */
export function offeredOptIns(plan: Plan): OfferedOptIn[] {
  const planned = plan.faces.filter((f) => f.status === 'planned');
  return plan.optIns
    .filter((o) => !o.applied && o.saving > 0)
    .map((o) => ({
      id: o.id,
      saving: o.saving,
      faces: o.faces,
      change: planned.flatMap((f) => f.optIns?.filter((x) => x.id === o.id) ?? [])[0]?.change ?? '',
    }))
    .toSorted((a, b) => b.saving - a.saving);
}

export interface FormatPlanOptions {
  style?: Style;
  /** List the opt-ins that weren't applied (default true; the CLI offers them as a choice instead). */
  optIns?: boolean;
}

export function formatPlan(plan: Plan, usage: UsageFileJson, o: FormatPlanOptions = {}): string {
  const s = o.style ?? plainStyle;
  const L: string[] = [];
  const planned = plan.faces.filter((f) => f.status === 'planned');
  const pages = pageBytes(plan, usage);
  if (planned.length) {
    const fileBytes = (f: FacePlan, role: string) => {
      const x = f.files?.find((y) => y.role === role);
      return x ? kb(x.bytes) : '-';
    };
    const perFace = (f: FacePlan) => {
      const ps = pages.map((p) => p.faces[f.id]).filter((x): x is { now: number; after: number } => !!x);
      return { now: median(ps.map((p) => p.now)), after: median(ps.map((p) => p.after)) };
    };
    // Over a site an earlier build split, the first column is the unsplit file, as the pages' is.
    const again = planned.some((f) => splitBefore(usage, f.id));
    L.push(
      ...table(
        [
          ['Face', again ? 'Before' : 'Now', 'Core', 'Ext', 'Rest', 'Median page', 'Saved'],
          ...planned.map((f) => {
            const m = perFace(f);
            return [
              label(f, usage),
              kb(splitBefore(usage, f.id) && f.source ? f.source.bytes : f.bytes!.now),
              fileBytes(f, 'core'),
              fileBytes(f, 'ext'),
              fileBytes(f, 'rest'),
              `${kb(m.now)} → ${kb(m.after)}`,
              savedPct(m.now, m.after),
            ];
          }),
        ],
        ['l', 'r', 'r', 'r', 'r', 'r', 'r'],
        (c, col, row) => (row === 0 ? s.dim(c) : col === 0 ? s.bold(c) : col === 6 ? s.green(c) : c),
      ),
    );
  } else L.push('Nothing to subset.');
  if (pages.length) {
    const now = median(pages.map((p) => p.now)),
      after = median(pages.map((p) => p.after));
    const max = pages.reduce((m, p) => (p.now - p.after > m.now - m.after ? p : m), pages[0]!);
    const d = change(now, after);
    L.push(
      '',
      `Font bytes per page: median ${kb(now)} → ${s.bold(kb(after))} (${s.bold((d.worse ? s.yellow : s.green)(d.text))})${
        max.now > max.after ? `; biggest drop ${max.page} ${kb(max.now)} → ${kb(max.after)}` : ''
      }`,
    );
    // A page pays for a whole extended file as soon as it draws one of its characters. The core
    // choice counts every page the same, so it can leave a page worse off than it was unsplit.
    const heavier = heavierPages(pages);
    if (heavier.length) {
      L.push('', s.bold(s.yellow('Pages that would download more than before')));
      for (const p of heavier.slice(0, 5)) {
        const why = p.extra.map((x) => {
          const f = planned.find((y) => y.id === x.face);
          const shown = x.chars
            .map((cp) => String.fromCodePoint(cp))
            .filter((ch) => /[\p{L}\p{N}\p{P}\p{S}]/u.test(ch));
          const list = shown.length ? ` (${shown.slice(0, 8).join(' ')}${shown.length > 8 ? ' …' : ''})` : '';
          return `${f ? label(f, usage) : x.face} ${x.role === 'ext' ? 'extended' : x.role} file, ${kb(x.bytes)}, for ${x.chars.length} character(s)${list}`;
        });
        L.push(`  ${p.page}  ${kb(p.now)} → ${kb(p.after)} (+${kb(p.after - p.now)})`, ...why.map((w) => `    ${w}`));
      }
      if (heavier.length > 5) L.push(`  … and ${heavier.length - 5} more`);
      L.push(
        s.dim(
          '  `--core-threshold 0` puts every used character in core: each page then loads a slightly larger core file and none of these.',
        ),
      );
    }
  }
  const chosen = planned.filter((f) => f.coreChoice);
  if (chosen.length) {
    L.push('', s.bold('Core choice: used characters put in core so the pages download less in total'));
    for (const f of chosen) {
      const c = f.coreChoice!;
      // The characters themselves, when they print: marks and controls would not read as a list.
      const shown = [...codePointsOf(parseUnicodeRange(c.added))]
        .map((cp) => String.fromCodePoint(cp))
        .filter((ch) => /[\p{L}\p{N}\p{P}\p{S}]/u.test(ch));
      const list = shown.length ? ` (${shown.slice(0, 12).join(' ')}${shown.length > 12 ? ' …' : ''})` : '';
      L.push(
        `  ${label(f, usage)}: ${c.count} character(s)${list}; ${c.coreOnly} of ${c.pages} page(s) load only the core file`,
      );
    }
  }
  const repaired = planned.filter((f) => f.repair);
  if (repaired.length) {
    L.push('', s.bold('Shaping repair: characters moved into core so words shape exactly as they did unsplit'));
    for (const f of repaired) {
      const cost = f.optIns?.find((x) => x.id === 'split-shaping')?.saving ?? 0;
      const w = f.repair!.words;
      L.push(
        `  ${label(f, usage)}: ${f.repair!.count} character(s), +${kb(cost)} core; e.g. ${w
          .slice(0, 4)
          .map((x) => JSON.stringify(x.trim()))
          .join(', ')}`,
      );
    }
  }
  const skipped = plan.faces.filter((f) => f.status !== 'planned');
  if (skipped.length) {
    L.push('', s.bold('Left as they are'));
    for (const f of skipped) L.push(`  ${label(f, usage)}: ${f.status === 'refused' ? 'refused, ' : ''}${f.reason}`);
  }
  const renames = planned.filter((f) => f.license?.rename);
  if (renames.length) {
    L.push('', s.bold('Renamed inside the font (the license reserves the name; CSS font-family unchanged)'));
    for (const f of renames) L.push(`  ${f.license!.rename!.from} → ${f.license!.rename!.to}`);
  }
  const offered = offeredOptIns(plan);
  if (offered.length && o.optIns !== false) {
    L.push('', s.bold('Opt-ins (would change rendering, not applied; `--allow <name>` applies one):'));
    for (const x of offered)
      L.push(
        `  ${s.cyan(x.id.padEnd(14))} saves ${s.green(kb(x.saving).padStart(8))}  ${s.dim(`${x.change}${x.faces > 1 ? ` (${x.faces} faces)` : ''}`)}`,
      );
  }
  const applied = plan.optIns.filter((x) => x.applied);
  if (applied.length)
    L.push('', `Applied opt-ins: ${applied.map((x) => `${s.cyan(x.id)} (saves ${kb(x.saving)})`).join(', ')}`);
  const notes = [
    ...new Set(
      planned.flatMap((f) =>
        (f.notes ?? []).filter((n) => !n.startsWith('no TrueType')).map((n) => `${f.family}: ${n}`),
      ),
    ),
  ];
  if (notes.length) {
    L.push('', s.bold('Notes'));
    for (const n of notes) L.push(`  ${n}`);
  }
  return L.join('\n');
}
